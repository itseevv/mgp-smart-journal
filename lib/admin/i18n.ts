export function normalizeAdminLocale(value: unknown): AdminLocale {
  return value === "zh-CN" ? "zh-CN" : "en";
}

export function translateAdmin(
  locale: AdminLocale,
  key: AdminTranslationKey,
  variables: AdminTranslationVariables = {},
) {
  const template = adminDictionaries[normalizeAdminLocale(locale)][key] ?? en[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name) =>
    Object.prototype.hasOwnProperty.call(variables, name)
      ? String(variables[name])
      : placeholder,
  );
}

