const textureWarningKeys: Record<string, AdminTranslationKey> = {
  "Texture is below the recommended 1080px width.": "warningTextureWidth",
  "Texture is below the recommended 1920px height.": "warningTextureHeight",
  "Texture aspect ratio is far from 9:16; adjust focus and zoom before publishing.":
    "warningTextureAspect",
  "Texture is a small file and may look low-resolution on export.":
    "warningTextureSmall",
};

export function adminStatusLabel(locale: AdminLocale, value: string) {
  const key = statusKeys[value];
  if (key) return translateAdmin(locale, key);
  return value.replaceAll("_", " ");
}

export function adminErrorMessage(locale: AdminLocale, code: unknown) {
  const key = typeof code === "string" ? errorKeys[code] : undefined;
  return translateAdmin(locale, key ?? "errorGeneric");
}

export function adminTextureWarning(locale: AdminLocale, warning: string) {
  return translateAdmin(
    locale,
    textureWarningKeys[warning] ?? "warningTextureGeneric",
  );
}

export function formatAdminDate(locale: AdminLocale, value: Date | string) {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

export function formatAdminDateOnly(locale: AdminLocale, value: Date | string) {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(locale, { dateStyle: "long" }).format(date);
}

export function formatAdminNumber(locale: AdminLocale, value: number) {
  return new Intl.NumberFormat(locale).format(value);
}
