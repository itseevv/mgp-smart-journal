import { createClient } from "@supabase/supabase-js";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !serviceKey) {
  throw new Error(
    "Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY before seeding an admin batch.",
  );
}

const args = new Map();
for (let index = 2; index < process.argv.length; index += 2) {
  args.set(process.argv[index], process.argv[index + 1]);
}

const productType = args.get("--product") ?? "journal";
const quantity = Number(args.get("--quantity") ?? "5");
const batchName =
  args.get("--name") ??
  (productType === "bookmark"
    ? "Development Bookmark Batch"
    : "Development Journal Batch");
const serialPrefix = args.get("--prefix") ?? null;
const issueRecovery = process.argv.includes("--recovery");

if (!["journal", "bookmark"].includes(productType)) {
  throw new Error("--product must be journal or bookmark.");
}
if (!Number.isInteger(quantity) || quantity < 1 || quantity > 500) {
  throw new Error("--quantity must be an integer from 1 to 500.");
}

const client = createClient(url, serviceKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const { data, error } = await client.rpc("admin_generate_capsule_batch", {
  requested_batch_name: batchName,
  requested_product_type: productType,
  requested_quantity: quantity,
  requested_serial_prefix: serialPrefix,
  requested_notes: "Generated by local Phase 7 seed script.",
  requested_actor: "local-seed",
});

if (error) throw error;
if (!data?.ok) throw new Error(`Batch generation failed: ${data?.code}`);

const output = {
  batchId: data.batchId,
  capsules: data.capsules.map((capsule) => ({
    ...capsule,
    localUrl: `http://localhost:3000/c/${capsule.publicToken}`,
  })),
  sensitiveRecoveryHandoff: [],
};

if (issueRecovery) {
  console.error(
    "DEVELOPMENT ONLY: generated Recovery Passcodes will be printed once.",
  );
  for (const capsule of data.capsules) {
    const response = await fetch(`${url}/functions/v1/capsule-access`, {
      method: "POST",
      headers: {
        apikey: serviceKey,
        Authorization: `Bearer ${serviceKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        action: "issue-recovery-code",
        capsuleId: capsule.id,
      }),
    });
    const result = await response.json();
    if (!response.ok || !result.ok || typeof result.recoveryCode !== "string") {
      output.sensitiveRecoveryHandoff.push({
        capsuleId: capsule.id,
        serialNumber: capsule.serialNumber,
        error: result.code ?? response.status,
      });
      continue;
    }
    output.sensitiveRecoveryHandoff.push({
      capsuleId: capsule.id,
      serialNumber: capsule.serialNumber,
      recoveryCode: result.recoveryCode,
      codeVersion: result.codeVersion,
    });
  }
}

console.log(JSON.stringify(output, null, 2));
